const { test } = require('node:test');
const assert = require('node:assert/strict');
const request = require('supertest');
const { createApp } = require('../backend/app.cjs');
const { isolatedDatabase } = require('./db-helper.cjs');
const { today } = require('../backend/validation.cjs');
test('PostgreSQL + HTTP: hábitos, datas idempotentes, progresso, isolamento e cascade', { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const pool = await isolatedDatabase(t);
  const { rows } = await pool.query("INSERT INTO usuarios(nome,email,senha_hash) VALUES ('A','a@example.com','test'),('B','b@example.com','test') RETURNING id");
  const [a,b] = rows.map(user => request(createApp({pool,authenticate(req,res,next) { req.user=user; next(); }})));
  const habit = (await a.post('/api/habitos').send({nome:'Ler',descricao:'Um capítulo',inicio:today()}).expect(201)).body.data;
  await a.put('/api/habitos/'+habit.id).send({nome:'Leitura',descricao:'Dois capítulos'}).expect(200);
  await b.put('/api/habitos/'+habit.id).send({nome:'Outro'}).expect(404);
  await b.delete('/api/habitos/'+habit.id).expect(404);
  const url='/api/habitos/'+habit.id+'/registros/'+today();
  await b.put(url).expect(404);
  await Promise.all([a.put(url).expect(204),a.put(url).expect(204)]);
  assert.equal((await pool.query('SELECT count(*) FROM registros_diarios')).rows[0].count,'1');
  const result=(await a.get('/api/habitos').expect(200)).body.data[0];
  assert.equal(result.nome,'Leitura');assert.equal(result.progresso,100);assert.equal(result.realizada,true);
  assert.equal((await b.get('/api/habitos')).body.data.length,0);
  await a.put('/api/habitos/'+habit.id+'/registros/2000-01-01').expect(400);
  await a.put('/api/habitos/'+habit.id+'/registros/2099-01-01').expect(400);
  await a.get('/api/habitos?data=2026-02-30').expect(400);
  await a.post('/api/habitos').send({nome:' '}).expect(400);
  await a.delete(url).expect(204);
  assert.equal((await a.get('/api/habitos')).body.data[0].progresso,0);
  await a.put(url).expect(204);
  await a.delete('/api/habitos/'+habit.id).expect(204);
  assert.equal((await pool.query('SELECT count(*) FROM registros_diarios')).rows[0].count,'0');
});
